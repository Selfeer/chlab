"""The base image a resolved binary runs inside.

Altinity's regression suite builds one image per package
(``helpers/cluster.py:1676``). ``clickhouse-common-static`` is a static binary, so chlab
instead builds this image once and bind-mounts the binary into it — every version reuses the
same image and startup costs seconds rather than a docker build.

The image is deliberately empty of ClickHouse itself: no server package, no stock configs.
Everything the server reads is generated by :mod:`chlab.core.configgen`.
"""

from __future__ import annotations

import hashlib
import subprocess

from .errors import ChlabError

BASE_DOCKERFILE = """\
FROM ubuntu:24.04

RUN set -eux; \\
    apt-get update; \\
    apt-get install -y --no-install-recommends ca-certificates tzdata curl locales; \\
    rm -rf /var/lib/apt/lists/*; \\
    mkdir -p \\
        /etc/clickhouse-server/config.d \\
        /etc/clickhouse-server/users.d \\
        /etc/clickhouse-keeper \\
        /var/lib/clickhouse \\
        /var/lib/clickhouse-keeper \\
        /var/log/clickhouse-server

ENV TZ=UTC
ENV LANG=C.UTF-8
"""

IMAGE_REPOSITORY = "chlab/base"
BUILD_TIMEOUT = 900


class ImageError(ChlabError):
    pass


def base_image_tag() -> str:
    """Tag derived from the Dockerfile, so editing it produces a different image."""
    digest = hashlib.sha256(BASE_DOCKERFILE.encode()).hexdigest()[:12]
    return f"{IMAGE_REPOSITORY}:{digest}"


def ensure_base_image(*, force: bool = False) -> str:
    """Build the base image if it is not already present, returning its tag."""
    tag = base_image_tag()
    if not force and _image_exists(tag):
        return tag

    result = subprocess.run(
        ["docker", "build", "-t", tag, "-"],
        input=BASE_DOCKERFILE,
        text=True,
        capture_output=True,
        timeout=BUILD_TIMEOUT,
    )
    if result.returncode != 0:
        raise ImageError(
            "could not build the chlab base image:\n"
            + (result.stderr.strip() or result.stdout.strip())
        )
    return tag


def _image_exists(tag: str) -> bool:
    result = subprocess.run(["docker", "image", "inspect", tag], capture_output=True, text=True)
    return result.returncode == 0
